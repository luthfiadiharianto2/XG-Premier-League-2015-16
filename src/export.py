"""Write tables, a machine-readable summary, a Markdown results file and the
dashboard's data.js. Every number in README/dashboard comes from here."""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pandas as pd


def _clean(obj):
    """Make numpy / NaN values JSON-safe."""
    if isinstance(obj, dict):
        return {str(k): _clean(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_clean(v) for v in obj]
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating, float)):
        f = float(obj)
        return None if math.isnan(f) or math.isinf(f) else f
    if isinstance(obj, np.bool_):
        return bool(obj)
    return obj


def _records(df: pd.DataFrame, decimals: int = 3) -> list[dict]:
    return _clean(df.round(decimals).to_dict(orient="records"))


def write_tables(out_dir: Path, tables: dict[str, pd.DataFrame]) -> None:
    tdir = out_dir / "tables"
    tdir.mkdir(parents=True, exist_ok=True)
    for name, df in tables.items():
        df.to_csv(tdir / f"{name}.csv", index=False, float_format="%.4f")


def write_summary(out_dir: Path, summary: dict) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "summary.json"
    path.write_text(json.dumps(_clean(summary), indent=2), encoding="utf-8")
    return path


def _md_table(df: pd.DataFrame, cols: dict[str, str], fmt: dict[str, str]) -> str:
    head = "| " + " | ".join(cols.values()) + " |"
    sep = "|" + "|".join("---:" if c in fmt else "---" for c in cols) + "|"
    lines = [head, sep]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(format(v, fmt[c]) if c in fmt and pd.notna(v) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


