def write_dashboard_data(path: Path, payload: dict) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(_clean(payload), separators=(",", ":"), ensure_ascii=False)
    path.write_text("// Generated by run_pipeline.py — do not edit by hand.\n"
                    f"window.XG_DATA = {body};\n", encoding="utf-8")
    return path


def shots_payload(shots: pd.DataFrame) -> dict:
    cols = ["match_id", "team", "opponent", "player", "minute", "x", "y", "xg", "statsbomb_xg",
            "is_goal", "body_part", "shot_type", "play_pattern"]
    df = shots[cols].copy()
    df["x"] = df.x.round(1)
    df["y"] = df.y.round(1)
    df["xg"] = df.xg.round(3)
    df["statsbomb_xg"] = df.statsbomb_xg.round(3)
    return {"cols": cols, "rows": _clean(df.to_numpy().tolist())}
